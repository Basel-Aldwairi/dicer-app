GAMES_CREATE_TABLE = '''
CREATE TABLE IF NOT EXISTS GAMES (
GAME_ID INTEGER PRIMARY KEY AUTOINCREMENT,
GAME_NAME VARCHAR UNIQUE NOT NULL,
DICE_ID INT NOT NULL,

FOREIGN KEY (DICE_ID) REFERENCES DICE(DICE_ID)
)
'''

